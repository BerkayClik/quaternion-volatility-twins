def main_table(s, freq):
    """Compact main-text table in three blocks (benchmarks, single-coin networks, pooled
    models); the block header replaces the per-row "pooled" tag to keep the table narrow."""
    rows = [r for r in MAIN_ROWS if r in s.index]
    t = s.loc[rows]
    titles = {"base": "Benchmarks (one model per coin)", "net": "Single-coin networks",
              "pooled": "Pooled models (one model for all 15 coins)"}
    with open(OUT_T / f"final_main_{freq}.tex", "w") as f:
        f.write("% generated by experiments/paper_tables_final.py\n")
        f.write("\\begin{tabular}{lrrrr}\n\\toprule\n")
        f.write("Model, inputs & MSE/HAR & better & signif. & QLIKE/HAR \\\\\n")
        prev = None
        for (gs, m), r in t.iterrows():
            block = "pooled" if m.endswith(POOL) else ("net" if m in LABEL and m not in
                    ("har", "harx", "hars", "harxs", "hars_x", "lgbm", "lgbms", "garch", "gjr", "ridge", "persistence",
                     "mean") else "base")
            if block != prev:
                f.write(f"\\midrule\n\\multicolumn{{5}}{{l}}{{\\emph{{{titles[block]}}}}} \\\\\n")
            prev = block
            name = label(gs, m).replace(", pooled)", ")").replace(" (pooled)", "")
            best = " \\textbf{%.3f}" % r.mse if r.mse == t.mse.min() else " %.3f" % r.mse
            f.write(f"{name} &{best} & {int(r.better)}/{int(r.n)} & {int(r.sig)}/{int(r.n)} & {r.qlike:.3f} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


def twin_table(settings):
    """Quaternion vs real twin, PMSE inputs: mean ratio, coins where quaternion is better,
    Holm-significant coins in each direction (family = coins), aggregate cross-coin DM."""
    rows = []
    for tag, df in settings.items():
        pooled = tag.startswith("pooled")
        for q, r in TWINS:
            q2, r2 = (q + POOL, r + POOL) if pooled else (q, r)
            x = df[(df.groupset == "PMSE") & df.model.isin([q2, r2])]
            if x.model.nunique() < 2:
                continue
            t = dm_table(x, {"range": ("PMSE", r2)})
            t["p_coins"] = holm(t.p)
            c = dm_cross(x, ("PMSE", q2), ("PMSE", r2))
            rows.append(dict(setting=tag, pair=f"{LABEL[q]} / {LABEL[r]}", ratio=t.rel_loss.mean(),
                             q_better=int((t.rel_loss < 1).sum()), n=len(t),
                             q_sig_better=int(((t.rel_loss < 1) & (t.p_coins < .05)).sum()),
                             r_sig_better=int(((t.rel_loss > 1) & (t.p_coins < .05)).sum()),
                             dm=c["dm_stat"], p=c["p"]))
    t = pd.DataFrame(rows)
    t["p_holm"] = holm(t.p)                    # family: all twin rows of the table
    spread = OUT_T / "review_seed_spread.csv"  # from experiments/paper_review_checks.py seeds
    if spread.exists():
        sp = pd.read_csv(spread)
        inv = {f"{LABEL[q]} / {LABEL[r]}": f"{q}/{r}" for q, r in TWINS}
        key = sp.set_index([sp.setting + " " + sp.freq, sp.pair])
        t["seed_min"] = [key.seed_min.get((st, inv[pr]), np.nan) for st, pr in zip(t.setting, t.pair)]
        t["seed_max"] = [key.seed_max.get((st, inv[pr]), np.nan) for st, pr in zip(t.setting, t.pair)]
    t.to_csv(OUT_T / "final_twins.csv", index=False)
    with open(OUT_T / "final_twins.tex", "w") as f:
        f.write("% generated by experiments/paper_tables_final.py\n")
        f.write("\\begin{tabular}{llrrrrrr}\n\\toprule\n")
        f.write("Setting & Quaternion / real & MSE ratio & Seed range & Q better & Q sig. & R sig. & DM (all coins) \\\\\n\\midrule\n")
        for _, r in t.iterrows():
            star = "$^{*}$" if r.p_holm < 0.05 else ""
            rng = f"{r.seed_min:.3f}--{r.seed_max:.3f}" if "seed_min" in t and not np.isnan(r.seed_min) else "--"
            f.write(f"{r.setting} & {r.pair} & {r.ratio:.3f} & {rng} & {r.q_better}/{r.n} & {r.q_sig_better} & "
                    f"{r.r_sig_better} & {r.dm:.2f}{star} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    return t


