def run(name):
    """Load a run by config name; None if it does not exist (yet)."""
    dirs = glob.glob(f"results/*/out/{name}_*") + glob.glob(f"results/*/{name}_*")
    dirs = [d for d in dirs if glob.glob(os.path.join(d, "preds", "*.npz"))]
    if not dirs:
        return None
    if len(dirs) > 1:
        raise RuntimeError(f"several runs for {name}: {dirs}")
    return load_run(dirs[0])


def setting(freq):
    """Single-coin and pooled range forecasts of one frequency, with HAR-X; None if missing."""
    single = run(f"final_single_{freq}")
    if single is None:  # HAR, the benchmark, lives in the single-coin run
        return None
    parts = [single, run(f"final_pool_{freq}"), run(f"final_harx_{freq}"), run(f"final_har_season_{freq}"),
             run(f"final_lgbm_{freq}"),
             # review round 8 (experiments/paper_round8_checks.py): HAR-S x and the lagged pooled LightGBM-S
             run(f"final_harsx_{freq}"), run(f"final_lgbmlags_{freq}")]
    parts = [p[p.task == "range"] for p in parts if p is not None]
    return pd.concat(parts) if parts else None


def label(gs, model):
    base = model[:-len(POOL)] if model.endswith(POOL) else model
    name = LABEL.get(base, base)
    if model.endswith(POOL):
        name = name[:-1] + ", pooled)" if name.endswith(")") else name + " (pooled)"
    elif base in ("lgbm", "lgbms"):  # LightGBM exists single-coin and pooled; name both explicitly
        name += " (single)"
    return name if model in ("har", "persistence", "mean", "garch", "gjr", "hars", "har_rv", "har_rv_s", "hars_x",
                             "har_lvl") else f"{name}, {gs}"


def summary_table(df, freq):
    """Mean MSE/HAR over coins, coins better than HAR, Holm-significant coins, mean QLIKE/HAR."""
    d = dm_table(df, {"range": ("P", "har")})
    q = dm_table(df, {"range": ("P", "har")}, loss="qlike")
    s = d.groupby(["groupset", "model"]).agg(mse=("rel_loss", "mean"), better=("rel_loss", lambda v: int((v < 1).sum())),
                                             n=("rel_loss", "size"))
    s["sig"] = d.assign(sig=(d.rel_loss < 1) & (d.p_holm < 0.05)).groupby(["groupset", "model"]).sig.sum().astype(int)
    s["qlike"] = q.groupby(["groupset", "model"]).rel_loss.mean()
    s = s.drop(index=[("PMSE", m) for m in ("har", "persistence", "mean", "garch", "gjr")], errors="ignore")
    s = s.sort_values("mse")
    s.to_csv(OUT_T / f"final_summary_{freq}.csv")
    with open(OUT_T / f"final_summary_{freq}.tex", "w") as f:
        f.write("% generated by experiments/paper_tables_final.py\n")
        f.write("\\begin{tabular}{lrrrr}\n\\toprule\n")
        f.write("Model, inputs & MSE/HAR & better & signif. & QLIKE/HAR \\\\\n\\midrule\n")
        for (gs, m), r in s.iterrows():
            f.write(f"{label(gs, m)} & {r.mse:.3f} & {int(r.better)}/{int(r.n)} & {int(r.sig)}/{int(r.n)} & {r.qlike:.3f} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    return s


