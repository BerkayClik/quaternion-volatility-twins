def _vs_har(df, har):
    """Mean over coins of MSE/HAR and number of coins better than HAR, per (groupset, model)."""
    d = dm_table(pd.concat([har, df]), {"range": ("P", "har")})
    return d.groupby(["groupset", "model"]).agg(mse=("rel_loss", "mean"),
                                                 better=("rel_loss", lambda v: int((v < 1).sum())),
                                                 n=("rel_loss", "size"))


def _pair(df, a, b):
    """Coin-mean MSE ratio a/b, coins where a is better, cross-coin DM p-value (a, b = (groupset, model))."""
    x = df[[(g, m) in (a, b) for g, m in zip(df.groupset, df.model)]]
    t = dm_table(x, {"range": b})
    c = dm_cross(x, a, b)
    return dict(ratio=t.rel_loss.mean(), better=int((t.rel_loss < 1).sum()), n=len(t), dm=c["dm_stat"], p=c["p"])


def _fmt_pair(r):
    # *: unadjusted p < 0.05; dagger: also Holm-adjusted p < 0.05 within the table
    star = "*" if r["p"] < 0.05 else ""
    star += "\\dagger" if r.get("p_holm", 1.0) < 0.05 else ""
    star = f"$^{{{star}}}$" if star else ""
    return f"{r['ratio']:.3f} & {r['better']}/{r['n']} & {r['dm']:.2f}{star}"


