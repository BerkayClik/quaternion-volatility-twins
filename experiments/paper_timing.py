"""
Training-step timing of the fused against the step-by-step quaternion LSTM (Appendix B.2).

    .venv/bin/python experiments/paper_timing.py [--device cuda|cpu|mps] [--reps 50]

For the flat QLSTM and the hierarchical H-QLSTM (meta) at the 20k-parameter budget of the
main grid (PMSE inputs, 4 groups; 4-hourly window W = 42; batch 128), it times one training
step (forward, MSE loss, backward, Adam update) with QuaternionLSTM.forward running either the
fused kernel (default) or the explicit time loop (_forward_loop). The two variants share the same
parameters and produce the same outputs up to rounding. Reports mean and standard deviation over
`reps` timed steps after warm-up, and writes docs/paper/manuscript/tables/r6_timing_<device>.csv
plus r6_timing.tex, which merges every device CSV present (`--tex-only` rebuilds just the table).
"""

import argparse
import os
import platform
import sys
import time

import numpy as np
import pandas as pd
import torch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from src.models.quaternion_lstm import QuaternionLSTM  # noqa: E402
from src.paper.models import build_matched  # noqa: E402

_FUSED = QuaternionLSTM.forward


def _loop(self, x, hx=None):
    return self._forward_loop(x, hx)


def sync(device):
    if device == "cuda":
        torch.cuda.synchronize()
    elif device == "mps":
        torch.mps.synchronize()


def time_steps(model, x, y, device, reps, warmup=10):
    opt = torch.optim.Adam(model.parameters(), lr=1e-3)
    times = []
    for i in range(warmup + reps):
        sync(device)
        t0 = time.perf_counter()
        opt.zero_grad(set_to_none=True)
        loss = torch.nn.functional.mse_loss(model(x).reshape(-1), y)
        loss.backward()
        opt.step()
        sync(device)
        if i >= warmup:
            times.append(time.perf_counter() - t0)
    return 1e3 * np.array(times)


TABLES = "docs/paper/manuscript/tables"
LABELS = {"qlstm": "QLSTM", "hq_meta": "H-QLSTM (meta)"}


def write_tex():
    lines = ["% generated by experiments/paper_timing.py", r"\begin{tabular}{llrrrrr}", r"\toprule",
             r"Device & Model & $H$ & Params & Fused (ms) & Loop (ms) & Speed-up \\", r"\midrule"]
    for dev in ("cuda", "mps", "cpu"):
        f = os.path.join(TABLES, f"r6_timing_{dev}.csv")
        if not os.path.exists(f):
            continue
        for _, r in pd.read_csv(f).iterrows():
            name = "GPU (" + r.device.replace("NVIDIA ", "") + ")" if dev == "cuda" else dev.upper()
            lines.append(f"{name} & {LABELS[r.model]} & {r.hidden} & {r.params:,} & "
                         f"{r.fused_ms:.2f} $\\pm$ {r.fused_sd:.2f} & {r.loop_ms:.1f} $\\pm$ {r.loop_sd:.1f} & "
                         f"{r.speedup:.1f}$\\times$ \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    with open(os.path.join(TABLES, "r6_timing.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--reps", type=int, default=50)
    ap.add_argument("--threads", type=int, default=2)
    ap.add_argument("--tex-only", action="store_true")
    a = ap.parse_args()
    if a.tex_only:
        write_tex()
        return
    torch.set_num_threads(a.threads)
    dev = a.device
    hw = torch.cuda.get_device_name(0) if dev == "cuda" else f"{platform.processor() or platform.machine()} ({dev})"
    n_groups, W, B = 4, 42, 128
    rows = []
    for name in ("qlstm", "hq_meta"):
        torch.manual_seed(0)
        model, hidden = build_matched(name, n_groups, 20000)
        model = model.to(dev).train()
        x = torch.randn(B, W, 4 * n_groups, device=dev)
        y = torch.randn(B, device=dev)
        with torch.no_grad():
            QuaternionLSTM.forward = _FUSED
            out_f = model(x)
            QuaternionLSTM.forward = _loop
            out_l = model(x)
        diff = float((out_f - out_l).abs().max())
        res = {}
        for variant, fwd in (("fused", _FUSED), ("loop", _loop)):
            QuaternionLSTM.forward = fwd
            res[variant] = time_steps(model, x, y, dev, a.reps)
        QuaternionLSTM.forward = _FUSED
        r = dict(device=hw, model=name, hidden=hidden, params=sum(p.numel() for p in model.parameters()),
                 batch=B, window=W, fused_ms=res["fused"].mean(), fused_sd=res["fused"].std(),
                 loop_ms=res["loop"].mean(), loop_sd=res["loop"].std(),
                 speedup=res["loop"].mean() / res["fused"].mean(), max_abs_diff=diff, torch=torch.__version__)
        rows.append(r)
        print(r, flush=True)
    t = pd.DataFrame(rows)
    t.to_csv(os.path.join(TABLES, f"r6_timing_{dev}.csv"), index=False)
    write_tex()
    print(t.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
