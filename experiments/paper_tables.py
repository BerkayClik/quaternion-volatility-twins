"""
Build every table and figure of the paper from saved run directories.

    .venv/bin/python experiments/paper_tables.py   # -> docs/paper/manuscript/{tables,figures}/

Run directories are discovered under results/ by config name, so re-running an
experiment (new config hash) is picked up automatically if only one exists.
"""

