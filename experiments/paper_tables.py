warnings.filterwarnings("ignore")
OUT_T, OUT_F = Path("docs/paper/manuscript/tables"), Path("docs/paper/manuscript/figures")
COINS = ["btc", "eth", "bnb", "sol", "xrp"]
NAMES = {"lstm": "LSTM", "qlstm": "QLSTM", "hq_concat": "H-QLSTM (concat)", "hq_meta": "H-QLSTM (meta)",
         "hq_gattn": "H-QLSTM (group attn.)", "har": "HAR", "ridge": "Ridge", "persistence": "Persistence",
         "mean": "Mean", "lstm_attn": "LSTM + TA", "qlstm_attn": "QLSTM + TA",
         "hq_concat_attn": "H-QLSTM (concat) + TA", "hq_meta_attn": "H-QLSTM (meta) + TA",
         "hq_gattn_attn": "H-QLSTM (group attn.) + TA"}


def run_dir(name):
    hits = glob.glob(f"results/*/out/{name}_*")
    if len(hits) != 1:
        raise RuntimeError(f"expected one run dir for {name}, found {hits}")
    return hits[0]


def label(gs, model):
    pooled = model.endswith("-pool")
    base = NAMES.get(model.removesuffix("-pool"), model)
    return f"{base}{' [pooled]' if pooled else ''} · {gs}"


def ratio_table(d, order):
    """rel_loss with significance marks: '+' better / '−' worse than benchmark (Holm 5%)."""
    t = d.pivot_table(index=["groupset", "model"], columns="dataset", values="rel_loss")[order]
    mark = d.assign(m=np.where(d.p_holm < 0.05, np.where(d.dm_stat < 0, "+", "−"), "")) \
            .pivot_table(index=["groupset", "model"], columns="dataset", values="m", aggfunc="first")[order]
    t["mean"] = t.mean(1)
    return t, mark


def save(t, mark, name, caption):
    t.round(4).to_csv(OUT_T / f"{name}.csv")
    show = t.copy()
    for c in show.columns:
        show[c] = show[c].map(lambda v: f"{v:.3f}")
        if c in mark.columns:
            show[c] = show[c] + mark[c].fillna("")
    show.index = [label(gs, m) for gs, m in show.index]
    with open(OUT_T / f"{name}.tex", "w") as f:
        f.write(f"% {caption}\n" + show.to_latex(escape=True))


COINS_FINAL = ["btc", "eth", "sol", "bnb", "xrp", "ada", "doge", "link", "ltc", "dot",
               "avax", "trx", "bch", "xlm", "atom"]


def datasets_table():
    """Samples of the final run: one row per coin, bars and first bar per frequency."""
    rows, ends = [], set()
    for coin in COINS_FINAL:
        r = {"coin": coin.upper()}
        for freq in ["1d", "4h", "1h"]:
            d = make_dataset(coin, freq, start="2023-01-01" if freq == "1h" else None)
            r[f"{freq}_bars"], r[f"{freq}_start"] = len(d.frame), d.frame.index[0].date()
            ends.add((freq, d.frame.index[-1]))
        rows.append(r)
    t = pd.DataFrame(rows)
    t.to_csv(OUT_T / "datasets.csv", index=False)
    end = {f: str(max(e for g, e in ends if g == f)) for f in ["1d", "4h", "1h"]}
    with open(OUT_T / "datasets.tex", "w") as f:
        f.write(f"% generated by experiments/paper_tables.py; last bars: {end}\n")
        f.write("\\begin{tabular}{lrlrlrl}\n\\toprule\n")
        f.write(" & \\multicolumn{2}{c}{Daily} & \\multicolumn{2}{c}{4-hourly} & \\multicolumn{2}{c}{Hourly} \\\\\n")
        f.write("\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n")
        f.write("Coin & Bars & Start & Bars & Start & Bars & Start \\\\\n\\midrule\n")
        for r in rows:
            f.write(f"{r['coin']} & " + " & ".join(f"{r[q + '_bars']:,} & {r[q + '_start']}" for q in ["1d", "4h", "1h"])
                    + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


def main_tables():
    main = load_run(run_dir("main"))
    o1 = [f"{c}_1d" for c in COINS if c != "xrp"]
    o4 = [f"{c}_4h" for c in COINS]
    rng = main[main.task == "range"]
    d = dm_table(rng, {"range": ("P", "har")})
    for order, tag in [(o1, "1d"), (o4, "4h")]:
        t, m = ratio_table(d[d.dataset.isin(order)], order)
        save(t, m, f"range_single_{tag}", f"MSE relative to HAR, single-coin, {tag}")
    ret = main[main.task == "return"]
    d = dm_table(ret, {"return": ("P", "persistence")})
    t, m = ratio_table(d, o1 + o4)
    save(t, m, "return_single", "MSE relative to the zero forecast, return task")
    return rng


def pooled_tables(rng_main):
    p4 = load_run(run_dir("pool_4h"))
    o4 = [f"{c}_4h" for c in COINS]
    single = rng_main[rng_main.dataset.isin(o4) & rng_main.model.isin(["har", "lstm", "qlstm", "hq_concat", "hq_meta"])]
    both = pd.concat([single, p4])
    t, m = ratio_table(dm_table(both, {"range": ("P", "har")}), o4)
    save(t, m, "range_pooled_4h", "MSE relative to HAR, single-coin vs pooled, 4h")
    for bench, tag in [(("P", "lstm-pool"), "vs_price_lstm"), (("PMSE", "lstm-pool"), "vs_lstm16"),
                       (("PMSE", "qlstm-pool"), "vs_qlstm16")]:
        d = dm_table(p4, {"range": bench})
        d = d[d.model.isin(["hq_meta-pool", "hq_concat-pool"]) & (d.groupset == "PMSE")]
        t, m = ratio_table(d, o4)
        save(t, m, f"pooled_4h_{tag}", f"pooled H-QLSTM vs {bench}")
    p1 = load_run(run_dir("pool_1d"))
    o1 = [f"{c}_1d" for c in COINS if c != "xrp"]
    t, m = ratio_table(dm_table(p1, {"range": ("P", "har")}), o1)
    save(t, m, "range_pooled_1d", "MSE relative to HAR, single vs pooled, 1d (folds end 2025-07-21)")
    return both


def hourly_tables():
    h = load_run(run_dir("hourly"))
    o = [f"{c}_1h" for c in COINS]
    rng = h[h.task == "range"]
    t, m = ratio_table(dm_table(rng, {"range": ("P", "har")}), o)
    save(t, m, "range_single_1h", "MSE relative to HAR, single-coin, 1h")
    for bench, tag in [(("P", "lstm"), "vs_price_lstm"), (("PMSE", "lstm"), "vs_lstm16"), (("PMSE", "qlstm"), "vs_qlstm16")]:
        d = dm_table(rng, {"range": bench})
        d = d[d.model.isin(["hq_meta", "hq_concat"]) & (d.groupset == "PMSE")]
        t, m = ratio_table(d, o)
        save(t, m, f"hourly_{tag}", f"hourly H-QLSTM vs {bench}")


def ablation_tables(rng_main):
    abl = load_run(run_dir("ablation"))
    keep = rng_main[rng_main.model.isin(["ridge", "lstm", "qlstm", "hq_concat", "hq_meta", "har"])]
    d = dm_table(pd.concat([keep, abl]), {"range": ("P", "har")})
    d["freq"] = d.dataset.str[-2:]
    t = d.pivot_table(index=["model", "groupset"], columns="freq", values="rel_loss", aggfunc="mean")
    t.round(4).to_csv(OUT_T / "ablation.csv")
    rows = []
    har = rng_main[(rng_main.model == "har") & (rng_main.groupset == "P")]
    for b in ["budget_2000", "budget_5000", "main"]:
        x = load_run(run_dir(b))
        x = x[(x.task == "range") & x.model.isin(["lstm", "qlstm", "hq_concat", "hq_meta"])]
        dd = dm_table(pd.concat([x, har]), {"range": ("P", "har")})
        dd["freq"], dd["budget"] = dd.dataset.str[-2:], b
        rows.append(dd)
    B = pd.concat(rows).pivot_table(index=["model", "groupset"], columns=["freq", "budget"], values="rel_loss")
    B.round(4).to_csv(OUT_T / "budget.csv")
    return t


def economic_tables():
    M, P = run_dir("main"), run_dir("pool_4h")
    sel = lambda d: d[d.dataset.str.endswith("4h") & (
        ((d.model == "har") & (d.groupset == "P")) | ((d.model == "lstm") & (d.groupset == "P")) |
        (d.model.isin(["lstm", "qlstm", "hq_meta"]) & (d.groupset == "PMSE")))]
    test = pd.concat([sel(load_preds(M)), load_preds(P)])
    val = pd.concat([sel(load_preds(M, split="val")), load_preds(P, split="val")])
    V = variance_forecasts(test, val)
    res, series = vol_target(V, "4h")
    res.round(4).to_csv(OUT_T / "vol_target_4h.csv", index=False)
    n = BARS_PER_YEAR["4h"]
    fees = []
    for (ds, gs, m), rp in series.items():
        b = series.get((ds, "P", "har"))
        if b is None or m == "har":
            continue
        k = min(len(b), len(rp))
        fees.append(dict(dataset=ds, groupset=gs, model=m,
                         fee_bp_g1=fko_fee(rp[:k], b[:k], 1) * n * 1e4, fee_bp_g10=fko_fee(rp[:k], b[:k], 10) * n * 1e4))
    pd.DataFrame(fees).round(1).to_csv(OUT_T / "fko_fee_4h.csv", index=False)
    vb = pd.concat([var_backtest(V, a, "fhs").assign(alpha=a) for a in (0.01, 0.05)] +
                   [var_backtest(V, a, "normal").assign(alpha=a, method="normal") for a in (0.01, 0.05)])
    vb.round(4).to_csv(OUT_T / "var_backtest_4h.csv", index=False)
    return V, series


# ---------------------------------------------------------------- figures
def fig_pooled(both):
    o4 = [f"{c}_4h" for c in COINS]
    d = dm_table(both, {"range": ("P", "har")})
    pairs = [("PMSE", "hq_meta", "H-QLSTM (meta), 16 feat."), ("PMSE", "lstm", "LSTM, 16 feat."),
             ("PMSE", "qlstm", "QLSTM, 16 feat."), ("P", "lstm", "LSTM, price only")]
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    w = 0.1
    for i, (gs, m, name) in enumerate(pairs):
        for j, suffix in enumerate(["", "-pool"]):
            v = d[(d.groupset == gs) & (d.model == m + suffix)].set_index("dataset").rel_loss.reindex(o4)
            ax.bar(np.arange(5) + (2 * i + j - 3.5) * w, v, w, label=f"{name}{' (pooled)' if suffix else ''}",
                   color=plt.cm.tab20(2 * i + (0 if suffix else 1)))
    ax.axhline(1, color="k", lw=0.8, ls="--")
    ax.set_xticks(range(5), [c.upper() for c in COINS])
    ax.set_ylabel("MSE / MSE(HAR)")
    ax.set_ylim(0.8, 1.1)
    ax.legend(fontsize=6.5, ncol=2, frameon=False)
    fig.tight_layout()
    fig.savefig(OUT_F / "pooled_vs_single_4h.pdf")
    plt.close(fig)


def fig_ablation(t):
    order = ["P", "PM", "PMS", "PMSE"]
    fig, ax = plt.subplots(figsize=(4.2, 3.0))
    for m, name in [("lstm", "LSTM"), ("qlstm", "QLSTM"), ("hq_concat", "H-QLSTM")]:
        v = [t.loc[(m if not (m == "hq_concat" and g == "PMSE") else "hq_meta", g), "4h"]
             if (m if not (m == "hq_concat" and g == "PMSE") else "hq_meta", g) in t.index else np.nan for g in order]
        ax.plot([4, 8, 12, 16], v, marker="o", label=name)
    ax.set_xlabel("number of input features (groups × 4)")
    ax.set_ylabel("mean MSE / MSE(HAR), 4h")
    ax.set_xticks([4, 8, 12, 16])
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(OUT_F / "ablation_features_4h.pdf")
    plt.close(fig)


def fig_vol_target(V, series):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8), sharey=False)
    for ax, ds in zip(axes, ["btc_4h", "eth_4h"]):
        t = V[V.dataset == ds].drop_duplicates("time").sort_values("time").time
        bh = np.expm1(V[V.dataset == ds].drop_duplicates("time").sort_values("time").r.to_numpy())
        ax.plot(t, np.cumprod(1 + bh), color="0.6", lw=0.8, label="buy & hold")
        for key, name in [(("P", "har"), "HAR"), (("PMSE", "hq_meta-pool"), "H-QLSTM (meta, pooled)")]:
            rp = series[(ds, *key)]
            ax.plot(t[: len(rp)], np.cumprod(1 + rp), lw=0.9, label=name)
        ax.set_title(ds.replace("_", " ").upper(), fontsize=9)
        ax.tick_params(axis="x", labelrotation=30, labelsize=7)
    axes[0].set_ylabel("wealth (vol-targeted, 40% p.a.)")
    axes[0].legend(fontsize=7, frameon=False)
    fig.tight_layout()
    fig.savefig(OUT_F / "vol_target_4h.pdf")
    plt.close(fig)


